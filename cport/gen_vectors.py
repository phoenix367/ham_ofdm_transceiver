FNV_OFFSET = 14695981039346656037
FNV_PRIME = 1099511628211
U64 = (1 << 64) - 1


def fnv64_i16(samples):
    h = FNV_OFFSET
    for s in np.asarray(samples, dtype=np.int64):
        h = ((h ^ (int(s) & 0xFFFF)) * FNV_PRIME) & U64
    return h


def fnv64_i64(values):
    h = FNV_OFFSET
    for v in np.asarray(values, dtype=np.int64):
        h = ((h ^ (int(v) & U64)) * FNV_PRIME) & U64
    return h


def gen_mode_roms():
    """Per-mode constants + preamble/pilot/LPF ROMs -> src/rom_modes.h."""
    out = ["/* generated by gen_vectors.py -- do not edit */",
           "#ifndef ROM_MODES_H", "#define ROM_MODES_H",
           "#include <stdint.h>", ""]
    ref = None
    for mode in LinkMode:
        tx = FixedTransmitter(mode)
        m = tx._m
        idx = (tuple(m.channel_indices), tuple(m._data_local_indices),
               tuple(m._pilot_local_indices))
        if ref is None:
            ref = idx
            out.append(carr("CHANNEL_IDX", m.channel_indices, "int16_t"))
            out.append(carr("DATA_LOCAL_IDX", m._data_local_indices, "int16_t"))
            out.append(carr("PILOT_LOCAL_IDX", m._pilot_local_indices, "int16_t"))
            out.append(carr("PILOT_RE", tx.pilot_rom[0], "int16_t"))
            out.append(carr("PILOT_IM", tx.pilot_rom[1], "int16_t"))
            out.append(carr("TX_LPF_TAPS", tx.lpf_q15, "int16_t"))
            out.append(f"#define N_CHANNEL {len(m.channel_indices)}")
            out.append(f"#define N_DATA_CARRIERS {len(m._data_local_indices)}")
            out.append(f"#define N_PILOTS {len(m._pilot_local_indices)}")
            out.append(f"#define CP_LEN {m.cyclic_prefix}")
            out.append(f"#define FFT_BINS {m.fft_bins}\n")
        else:
            assert idx == ref, "carrier layout differs between modes"
        out.append(f"#define SYM_TILE_{mode.name} {m.sym_tile}")
        out.append(f"#define PREAMBLE_LEN_{mode.name} {len(tx.preamble_rom)}")
        # the preamble is perfectly periodic piecewise -- store only the
        # unique blocks (32+64+128 samples vs up to 69664): tone field A
        # (2T tiles of a 32-sample block), tone field B (T tiles of a
        # 64-sample block), ZC symbol (CP = tail of one 128-sample tile,
        # then sym_tile tiles). tx.c re-expands with modulo indexing.
        pre = [int(v) for v in tx.preamble_rom]
        n_tail = m.cyclic_prefix + m.sym_tile * m.fft_bins
        T = (len(pre) - n_tail) // (3 * m.fft_bins)
        assert 3 * T * m.fft_bins + n_tail == len(pre)
        tone_a = pre[:32]
        tone_b = pre[2 * T * m.fft_bins:2 * T * m.fft_bins + 64]
        zc = pre[3 * T * m.fft_bins + m.cyclic_prefix:
                 3 * T * m.fft_bins + m.cyclic_prefix + m.fft_bins]
        rebuilt = ([tone_a[i % 32] for i in range(2 * T * m.fft_bins)]
                   + [tone_b[i % 64] for i in range(T * m.fft_bins)]
                   + zc[m.fft_bins - m.cyclic_prefix:]
                   + zc * m.sym_tile)
        assert rebuilt == pre, f"{mode.name}: preamble not block-periodic"
        out.append(f"#define PRE_TONE_TILES_{mode.name} {T}")
        out.append(carr(f"PRE_TONEA_{mode.name}", tone_a, "int16_t"))
        out.append(carr(f"PRE_TONEB_{mode.name}", tone_b, "int16_t"))
        out.append(carr(f"PRE_ZC_{mode.name}", zc, "int16_t"))

    # --- RX demod constants -------------------------------------------------
    rx0 = FixedReceiver(LinkMode.NORMAL)
    m0 = rx0._m
    out.append(carr("PILOT_CARRIERS", m0._pilot_carriers.astype(int), "int16_t"))
    out.append(carr("PILOT_CONJ_RE", rx0.pilot_conj_rom[0], "int16_t"))
    out.append(carr("PILOT_CONJ_IM", rx0.pilot_conj_rom[1], "int16_t"))
    out.append(carr("INTERP_LO", [i[0] for i in rx0.interp], "int16_t"))
    out.append(carr("INTERP_HI", [i[1] for i in rx0.interp], "int16_t"))
    out.append(carr("INTERP_W", [i[2] for i in rx0.interp], "int32_t"))
    for mode in LinkMode:
        rx = FixedReceiver(mode)
        assert [tuple(t) for t in rx.interp] == [tuple(t) for t in rx0.interp]
        out.append(f"#define N_SEARCH_{mode.name} {len(rx.search_words)}")
        out.append(carr(f"SEARCH_WORDS_{mode.name}",
                        [int(w) for w in rx.search_words], "int32_t"))
    out.append(f"#define COARSE_GATE_Q4_C {FixedReceiver.COARSE_GATE_Q4}")

    # --- detection constants (tone + ZC stages), per mode -------------------
    for mode in LinkMode:
        rx = FixedReceiver(mode)
        nm = mode.name
        out += [f"#define DET_B_{nm} {rx.B}",
                f"#define DET_T_{nm} {rx.T}",
                f"#define DET_MAX_SHIFT_{nm} {rx.max_shift}",
                f"#define DET_NEWMAN_THR_Q10_{nm} {rx.newman_thr_q10}",
                f"#define DET_WORD_PER_BIN_{nm} {rx.word_per_fine_bin}",
                f"#define DET_N_MASK_BINS_{nm} {rx.n_mask_bins}",
                carr(f"DET_MASK0_{nm}", rx.masks[0], "uint8_t"),
                carr(f"DET_MASK1_{nm}", rx.masks[1], "uint8_t"),
                f"#define ZC_L_{nm} {rx.zc_L}",
                f"#define ZC_G_{nm} {rx.zc_G}",
                f"#define ZC_GROUPS_{nm} {rx.zc_groups}",
                f"#define ZC_REF_ENERGY_{nm} {rx.zc_ref_energy}",
                f"#define ZC_PRE_BLOCK_LEN_{nm} {rx.preamble_block_len}",
                f"#define ZC_THR_Q10_{nm} {rx.zc_thr_q10}",
                f"#define N_ZC_HYPS_{nm} {len(rx.zc_hyp_words)}",
                carr(f"ZC_HYP_WORDS_{nm}",
                     [int(w) for w in rx.zc_hyp_words], "int32_t"),
                carr(f"ZC_ROM_RE_{nm}", rx.zc_rom[0], "int16_t"),
                carr(f"ZC_ROM_IM_{nm}", rx.zc_rom[1], "int16_t")]
    # --- RX extras: calibration ROM, SNR-estimator constants ----------------
    out.append(carr("RECAL_ROM", FixedReceiver.RECAL_ROM, "int16_t"))
    out.append(carr("LOG2_FRAC_Q4", FixedReceiver.LOG2_FRAC_Q4, "int16_t"))
    out.append(f"#define SNR_CAL_DB {float(FixedReceiver.SNR_CAL_DB)!r}")
    out.append(f"#define TEN_LOG10_2 {float(10.0 * np.log10(2.0))!r}")
    for mode in LinkMode:
        rx = FixedReceiver(mode)
        out.append(f"#define TILE_DB_{mode.name} {float(rx._tile_db)!r}")
    out.append("#endif /* ROM_MODES_H */")
    (HERE / "src" / "rom_modes.h").write_text("\n".join(out))
    print("wrote src/rom_modes.h")


def gen_link_rom():
    """Rate ladder + controller scenario vectors -> src/rom_link.h."""
    from ofdm_phy.link import LADDER, LinkControl, LinkController
    out = ["/* generated by gen_vectors.py -- do not edit */",
           "#ifndef ROM_LINK_H", "#define ROM_LINK_H",
           "#include <stdint.h>", "",
           f"#define LADDER_N {len(LADDER)}"]
    out.append(carr("LADDER_MODE", [r.mode.value for r in LADDER], "int16_t"))
    out.append(carr("LADDER_MOD", [r.mod.value for r in LADDER], "int16_t"))
    out.append(carr("LADDER_SPD", [r.spd.value for r in LADDER], "int16_t"))
    out.append("static const double LADDER_SENS[LADDER_N] = { "
               + ", ".join(repr(float(r.sens_db)) for r in LADDER) + " };")
    out.append("static const double LADDER_RATE[LADDER_N] = { "
               + ", ".join(repr(float(r.user_rate)) for r in LADDER) + " };")

    # LC word golden vectors (incl. round-half-even edges)
    lcs = [LinkControl(seq=3, ack=1, req_rung=12, snr_db=-3.0,
                       freq_corr_hz=-48.0, flags=5),
           LinkControl(seq=0, ack=0, req_rung=0, snr_db=-24.0,
                       freq_corr_hz=0.0, flags=2),
           LinkControl(seq=2, ack=3, req_rung=15, snr_db=6.0,
                       freq_corr_hz=120.0, flags=7),
           LinkControl(seq=1, ack=2, req_rung=7, snr_db=-23.0,  # .5 rounding
                       freq_corr_hz=-4.0, flags=1),
           LinkControl(seq=1, ack=0, req_rung=3, snr_db=-21.0,  # .5 rounding
                       freq_corr_hz=12.0, flags=0)]
    out.append(carr("LC_PACKED", [lc.pack() for lc in lcs], "int32_t"))
    for i, lc in enumerate(lcs):
        u = LinkControl.unpack(lc.pack())
        out.append(f"#define LC{i}_SEQ {u.seq}")
        out.append(f"#define LC{i}_ACK {u.ack}")
        out.append(f"#define LC{i}_RUNG {u.req_rung}")
        out.append(f"#define LC{i}_SNR {float(u.snr_db)!r}")
        out.append(f"#define LC{i}_FREQ {float(u.freq_corr_hz)!r}")
        out.append(f"#define LC{i}_FLAGS {u.flags}")

    # controller parity trace: scripted ops, python outputs as golden.
    # op codes: 0 rx_frame(snr, req, report, t); 1 -> q=rx_request(t);
    # 2 -> q=tx_rung(t); 3 on_timeout; 4 on_ack; 5 note_outcome(rung, ok);
    # 6 -> q=filtered_snr(t)*1000 rounded; 7 -> q=tx_rung_for_class(t, ctl)
    ctl = LinkController()
    ops = []

    def rx(snr, req, rep, t):
        ctl.on_rx_frame(snr, LinkControl(req_rung=req, snr_db=rep), t)
        ops.append((0, snr, req, rep, t, 0))

    def q_req(t):
        ops.append((1, 0, 0, 0, t, ctl.rx_request(t)))

    def q_tx(t):
        ops.append((2, 0, 0, 0, t, ctl.tx_rung(t)))

    def q_snr(t):
        ops.append((6, 0, 0, 0, t, int(round(ctl.filtered_snr(t) * 1000))))

    def q_txc(t):
        ops.append((7, 0, 0, 0, t, ctl.tx_rung_for_class(t, "control")))

    # bootstrap + fast start
    q_req(0.0); q_tx(0.0)
    rx(-16.0, 0, -24.0, 1.0); q_req(1.5); q_snr(1.5)
    rx(-8.0, 3, -6.0, 10.0); rx(-7.5, 4, -6.0, 20.0)
    rx(-7.8, 5, -5.8, 30.0); q_req(31.0); q_tx(31.0); q_txc(31.0); q_snr(31.0)
    # upshift with margin
    rx(-2.0, 7, -1.0, 40.0); rx(-1.5, 8, -0.5, 50.0); rx(-1.8, 8, -0.4, 55.0)
    q_req(56.0); q_tx(56.0)
    # fade: downshift + report cap
    rx(-12.0, 2, -13.0, 60.0); rx(-12.5, 1, -13.5, 62.0)
    rx(-12.2, 1, -13.2, 64.0); q_req(65.0); q_tx(65.0)
    # loss fallback
    ops.append((3, 0, 0, 0, 66.0, 0)); ctl.on_timeout()
    ops.append((3, 0, 0, 0, 70.0, 0)); ctl.on_timeout()
    q_tx(71.0)
    ops.append((3, 0, 0, 0, 74.0, 0)); ctl.on_timeout()
    ops.append((3, 0, 0, 0, 78.0, 0)); ctl.on_timeout()
    q_tx(79.0)
    ops.append((4, 0, 0, 0, 80.0, 0)); ctl.on_ack()
    q_tx(81.0)
    # learned offsets
    for k in range(4):
        ops.append((5, 6, 0, 0, 82.0 + k, 0)); ctl.note_outcome(6, False)
    q_tx(86.0)
    ops.append((5, 6, 1, 0, 87.0, 0)); ctl.note_outcome(6, True)
    q_tx(88.0)
    # inbound silence decay + history purge
    q_req(120.0); q_req(200.0); q_snr(200.0)
    # stale peer request decay
    q_tx(300.0)

    out.append(f"#define CTL_OPS_N {len(ops)}")
    out.append(carr("CTL_OP", [o[0] for o in ops], "int16_t"))
    out.append("static const double CTL_A[CTL_OPS_N] = { "
               + ", ".join(repr(float(o[1])) for o in ops) + " };")
    out.append(carr("CTL_B", [o[2] for o in ops], "int16_t"))
    out.append("static const double CTL_C[CTL_OPS_N] = { "
               + ", ".join(repr(float(o[3])) for o in ops) + " };")
    out.append("static const double CTL_T[CTL_OPS_N] = { "
               + ", ".join(repr(float(o[4])) for o in ops) + " };")
    out.append(carr("CTL_WANT", [o[5] for o in ops], "int32_t"))
    out.append("#endif /* ROM_LINK_H */")
    (HERE / "src" / "rom_link.h").write_text("\n".join(out))
    print("wrote src/rom_link.h")


